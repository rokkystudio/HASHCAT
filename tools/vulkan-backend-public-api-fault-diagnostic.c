/**
 * Verify production four-stage Vulkan cleanup after API-call failures.
 *
 * The executable links the unchanged backend_vulkan_kernel implementation
 * with a test-only ld.lld --wrap driver. Five explicit scenarios interrupt
 * the final buffer, final shader module, final Compute pipeline, queue submit
 * or fence wait. Earlier Vulkan calls are real. After each returned error the
 * production executor releases its VkDevice resources, the interceptor is
 * disabled, and a fresh four-stage device under the same VkInstance must
 * execute four public Compute dispatches and verify all 256 output words.
 *
 * Injected VkResults are generated by the test linker and are never described
 * as physical driver failures. No HASHCAT password candidate, digest, salt or
 * hashing scheduler participates in this diagnostic.
 */

#include "backend_vulkan.h"
#include "backend_vulkan_kernel.h"
#include "vulkan-backend-public-api-fault-driver.h"

#include <inttypes.h>
#include <stdio.h>
#include <string.h>

typedef struct backend_vulkan_public_api_fault_scenario
{
  backend_vulkan_public_api_fault_site_t site;
  const char *name;
  uint32_t fail_on_attempt;
  VkResult result;
  uint32_t expected_real_submissions;
} backend_vulkan_public_api_fault_scenario_t;

static const backend_vulkan_public_api_fault_scenario_t
  backend_vulkan_public_api_fault_scenarios[] =
{
  {
    BACKEND_VULKAN_PUBLIC_API_FAULT_CREATE_BUFFER,
    "create_buffer",
    5u,
    VK_ERROR_OUT_OF_DEVICE_MEMORY,
    0u
  },
  {
    BACKEND_VULKAN_PUBLIC_API_FAULT_CREATE_SHADER_MODULE,
    "create_shader_module",
    4u,
    VK_ERROR_OUT_OF_DEVICE_MEMORY,
    0u
  },
  {
    BACKEND_VULKAN_PUBLIC_API_FAULT_CREATE_COMPUTE_PIPELINE,
    "create_compute_pipeline",
    4u,
    VK_ERROR_OUT_OF_DEVICE_MEMORY,
    0u
  },
  {
    BACKEND_VULKAN_PUBLIC_API_FAULT_QUEUE_SUBMIT,
    "queue_submit",
    1u,
    VK_ERROR_DEVICE_LOST,
    0u
  },
  {
    BACKEND_VULKAN_PUBLIC_API_FAULT_FENCE_WAIT,
    "fence_wait",
    1u,
    VK_ERROR_DEVICE_LOST,
    1u
  }
};

/**
 * Confirm that the public Vulkan diagnostic did not register a hash device.
 *
 * The information-mode executor uses only the Vulkan catalogue and temporary
 * local VkDevice objects. Ordinary backend scheduling fields must remain
 * untouched before and after every injected error and healthy recovery.
 */
static int backend_api_fault_scheduler_is_clean (
  const backend_ctx_t *backend)
{
  return backend != NULL
      && backend->vulkan_session == NULL
      && backend->backend_devices_cnt == 0
      && backend->devices_param == NULL
      && backend->enabled == false;
}

/**
 * Run one test-linked API failure followed by one healthy four-stage device.
 *
 * The selected wrapped call returns the scenario's synthetic VkResult at its
 * exact one-based attempt. The production executor must propagate that value,
 * execute one real vkDeviceWaitIdle during cleanup, and leave HASHCAT
 * scheduling state unchanged. The interceptor is then disarmed before a new
 * production four-stage job performs four real dispatches and 256 CPU checks.
 */
static int backend_api_fault_run_scenario (
  backend_ctx_t *backend,
  const backend_vulkan_public_api_fault_scenario_t *scenario)
{
  VkResult result = backend_vulkan_public_api_fault_arm (
    scenario->site,
    scenario->fail_on_attempt,
    scenario->result,
    stdout
  );

  if (result != VK_SUCCESS)
  {
    fprintf (
      stderr,
      "BACKEND_API_FAULT_ARM_FAILED"
      " site=%s"
      " result=%d\n",
      scenario->name,
      result
    );

    return 1;
  }

  const VkResult fault_result = backend_vulkan_kernel_verify_chain4 (
    backend, 0u, stdout
  );

  backend_vulkan_public_api_fault_counts_t counts = { 0 };

  const VkResult snapshot_result =
    backend_vulkan_public_api_fault_snapshot (&counts);

  const VkResult disarm_result =
    backend_vulkan_public_api_fault_disarm ();

  if (snapshot_result != VK_SUCCESS
   || disarm_result != VK_SUCCESS)
  {
    fprintf (
      stderr,
      "BACKEND_API_FAULT_STATE_FAILED"
      " site=%s"
      " snapshot=%d"
      " disarm=%d\n",
      scenario->name,
      snapshot_result,
      disarm_result
    );

    return 1;
  }

  if (fault_result != scenario->result
   || counts.attempts != scenario->fail_on_attempt
   || counts.real_calls != scenario->fail_on_attempt - 1u
   || counts.real_submissions != scenario->expected_real_submissions
   || counts.real_waits != 0u
   || counts.device_wait_idle_calls != 1u
   || counts.wait_idle_result != VK_SUCCESS
   || counts.injections != 1u
   || counts.blocked != 0u
   || counts.first_error != scenario->result
   || backend_api_fault_scheduler_is_clean (backend) == 0)
  {
    fprintf (
      stderr,
      "BACKEND_API_FAULT_CONTRACT_FAILED"
      " site=%s"
      " fault_result=%d"
      " attempts=%" PRIu32
      " real_calls=%" PRIu32
      " real_submissions=%" PRIu32
      " real_waits=%" PRIu32
      " wait_idle_calls=%" PRIu32
      " wait_idle_result=%d"
      " injected=%" PRIu32
      " blocked=%" PRIu32
      " first_error=%d"
      " scheduled=%d\n",
      scenario->name,
      fault_result,
      counts.attempts,
      counts.real_calls,
      counts.real_submissions,
      counts.real_waits,
      counts.device_wait_idle_calls,
      counts.wait_idle_result,
      counts.injections,
      counts.blocked,
      counts.first_error,
      backend_api_fault_scheduler_is_clean (backend) == 0
    );

    return 1;
  }

  result = backend_vulkan_kernel_verify_chain4 (
    backend, 0u, stdout
  );

  if (result != VK_SUCCESS
   || backend_api_fault_scheduler_is_clean (backend) == 0)
  {
    fprintf (
      stderr,
      "BACKEND_API_FAULT_RECOVERY_FAILED"
      " site=%s"
      " result=%d"
      " scheduled=%d\n",
      scenario->name,
      result,
      backend_api_fault_scheduler_is_clean (backend) == 0
    );

    return 1;
  }

  fprintf (
    stdout,
    "BACKEND_API_FAULT_RECOVERY_PASS"
    " site=%s"
    " fail_on_attempt=%" PRIu32
    " injected_result=%d"
    " prior_real_submissions=%" PRIu32
    " wait_idle_calls=%" PRIu32
    " new_device=1"
    " dispatches=4"
    " verified_words=256"
    " real_driver_failure=0"
    " password_inputs=0 scheduled=0\n",
    scenario->name,
    scenario->fail_on_attempt,
    scenario->result,
    counts.real_submissions,
    counts.device_wait_idle_calls
  );

  return 0;
}

/**
 * Run all five API-boundary failure paths under one real Vulkan instance.
 *
 * Opens the production backend catalogue for the requested minimum API and
 * executes each synthetic failure/recovery pair in fixed order. Every pair
 * creates and destroys its own faulted VkDevice and its own healthy recovery
 * VkDevice while the catalogue VkInstance stays live. The catalogue closes
 * only after all five pairs succeed.
 */
static int backend_api_fault_trial (uint32_t minimum_api)
{
  backend_ctx_t backend = { 0 };

  VkResult result = backend_vulkan_catalog_open (
    &backend, minimum_api, stdout
  );

  if (result != VK_SUCCESS)
  {
    fprintf (
      stderr,
      "BACKEND_API_FAULT_CATALOG_FAILED result=%d\n",
      result
    );

    return 1;
  }

  int exit_status = 1;

  if (backend.vulkan_catalog == NULL
   || backend.vulkan_devices_cnt == 0u
   || backend_api_fault_scheduler_is_clean (&backend) == 0)
  {
    fprintf (
      stderr,
      "BACKEND_API_FAULT_CATALOG_INVALID\n"
    );

    goto cleanup;
  }

  const uint32_t scenario_count =
    (uint32_t) (
      sizeof (backend_vulkan_public_api_fault_scenarios)
      / sizeof (backend_vulkan_public_api_fault_scenarios[0])
    );

  for (uint32_t i = 0u; i < scenario_count; i++)
  {
    if (backend_api_fault_run_scenario (
        &backend,
        &backend_vulkan_public_api_fault_scenarios[i]) != 0)
    {
      goto cleanup;
    }
  }

  exit_status = 0;

cleanup:
  result = backend_vulkan_catalog_close (&backend);

  if (result != VK_SUCCESS
   || backend.vulkan_catalog != NULL
   || backend.vulkan_devices_cnt != 0u
   || backend.vulkan_session != NULL)
  {
    fprintf (
      stderr,
      "BACKEND_API_FAULT_CATALOG_CLOSE_FAILED result=%d\n",
      result
    );

    exit_status = 1;
  }

  return exit_status;
}

/**
 * Execute the five production-executor API failure scenarios for Vulkan 1.0
 * or 1.1.
 *
 * Requires exactly "--minimum 1.0" or "--minimum 1.1". Returns 0 after five
 * synthetic API failures, five complete production cleanups and five healthy
 * four-stage recovery devices. Returns 2 for malformed CLI and 1 for any
 * unexpected driver, ownership, recovery or scheduler result.
 */
int main (int argc, char **argv)
{
  if (argc != 3
   || strcmp (argv[1], "--minimum") != 0
   || (strcmp (argv[2], "1.0") != 0
    && strcmp (argv[2], "1.1") != 0))
  {
    fprintf (
      stderr,
      "Usage: %s --minimum 1.0|1.1\n",
      argv[0]
    );

    return 2;
  }

  const uint32_t minimum_api =
    strcmp (argv[2], "1.0") == 0
      ? VK_API_VERSION_1_0 : VK_API_VERSION_1_1;

  if (backend_api_fault_trial (minimum_api) != 0)
  {
    return 1;
  }

  fprintf (
    stdout,
    "BACKEND_API_FAULT_DIAGNOSTIC_PASS"
    " api=%s"
    " scenarios=5"
    " injected=5"
    " cleanup_wait_idle=5"
    " recovered_devices=5"
    " recovered_dispatches=20"
    " verified_words=1280"
    " real_submit_before_wait_fault=1"
    " real_driver_failures=0"
    " password_inputs=0 scheduled=0\n",
    argv[2]
  );

  return 0;
}
